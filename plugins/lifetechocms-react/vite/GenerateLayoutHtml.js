
import fs from 'node:fs';
import path from 'node:path';

export function generateLayoutHtml({
  outputDirectory,
  projectRoot,
  viewsDirectory = 'src/Views',
  themeName
}) {
  const manifestPath = path.join(
    outputDirectory, '.vite', 'manifest.json'
  );

  const manifest = JSON.parse(
    fs.readFileSync(manifestPath, 'utf8')
  );

  const layoutsOutput = path.join(outputDirectory, 'Layouts');
  const viewsOutput = path.join(outputDirectory, 'Views');

  fs.mkdirSync(layoutsOutput, { recursive: true });
  fs.mkdirSync(viewsOutput, { recursive: true });

  // Generate Layout HTML resources
  const entries = Object.entries(manifest).filter(
    ([key, value]) =>
      key.startsWith('virtual:lifetech-layout-') &&
      value.isEntry
  );

  if (entries.length === 0) {
    throw new Error('LifeTechOCMS: No Layout entries found.');
  }

  for (const [key, entry] of entries) {
    const layoutName = key.replace(
      'virtual:lifetech-layout-', ''
    );

    const cssFiles = new Set();
    const visited = new Set();

    function collectCss(chunkKey) {
      if (visited.has(chunkKey)) return;
      visited.add(chunkKey);

      const chunk = manifest[chunkKey];
      if (!chunk) return;

      for (const css of chunk.css ?? []) {
        cssFiles.add(css);
      }

      for (const imported of chunk.imports ?? []) {
        collectCss(imported);
      }
    }

    collectCss(key);

    const assetUrl = file =>
      `<?= ltThemePath() ?>/${themeName}/${file}`;

    const cssTags = [...cssFiles]
      .map(file =>
        `<link rel="stylesheet" href="${assetUrl(file)}">`
      )
      .join('\n');

    const html = [
      '<!-- Generated by @lifetechocms/react -->',
      '<div id="lt-react-layout"></div>',
      '',
      '<div id="lt-dynamic-content" hidden>',
      '    <?php dddm::loadDynamicContent(); ?>',
      '</div>',
      '',
      cssTags,
      `<script type="module" src="${assetUrl(entry.file)}"></script>`,
      ''
    ].join('\n');

    fs.writeFileSync(
      path.join(layoutsOutput, `${layoutName}.html`),
      html,
      'utf8'
    );

    console.log(
      `[LifeTechOCMS] Generated Layout: ${layoutName}.html`
    );
  }

  // Generate View HTML resources
  const sourceViews = path.resolve(projectRoot, viewsDirectory);

  if (!fs.existsSync(sourceViews)) {
    throw new Error(
      `LifeTechOCMS: Views directory not found: ${sourceViews}`
    );
  }

  const viewFiles = fs.readdirSync(sourceViews)
    .filter(file => file.endsWith('.jsx'))
    .sort();

  for (const file of viewFiles) {
    const viewName = path.basename(file, '.jsx');

    const html = [
      '<!-- Generated by @lifetechocms/react -->',
      `<div data-lt-view="${viewName}"></div>`,
      ''
    ].join('\n');

    fs.writeFileSync(
      path.join(viewsOutput, `${viewName}.html`),
      html,
      'utf8'
    );

    console.log(
      `[LifeTechOCMS] Generated View: ${viewName}.html`
    );
  }
}
